    async def upload(self, ident: str, body: bytes | None = None, token: str = harness.APP_TOKEN, path: str | None = None, mime: str = "image/png"):
        return await self.client.put(path or f"/api/v1/images/{ident}", content=body if body is not None else png(),
                                     headers={"Authorization": f"Bearer {token}", "Content-Type": mime})

    async def test_raw_upload_metadata_content_and_immutable_idempotency(self):
        ident = image_id(); body = png(2, 3)
        response = await self.upload(ident, body)
        self.assertEqual(response.status_code, 200)
        self.assertEqual(set(response.json()), FIELDS)
        self.assertEqual(response.json(), {"image_id": ident, "mime_type": "image/png", "size_bytes": len(body),
                                          "sha256": hashlib.sha256(body).hexdigest(), "width": 2, "height": 3})
        self.assertEqual((await self.upload(ident, body)).json(), response.json())
        self.assertEqual((await self.upload(ident, png(2, 3, b"\0\0\0"))).status_code, 409)
        content = await self.client.get(f"/api/v1/images/{ident}/content")
        self.assertEqual(content.content, body)
        self.assertEqual(content.headers["cache-control"], "no-store")
        self.assertEqual(content.headers["content-type"], "image/png")
        self.assertEqual(content.headers["x-content-type-options"], "nosniff")
        self.assertEqual(self.app.state.db.execute("SELECT COUNT(*) FROM v1_images").fetchone()[0], 1)

