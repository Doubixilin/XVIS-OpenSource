def image_id() -> str:
    return "i-" + uuid.uuid4().hex


def png_chunk(kind: bytes, body: bytes) -> bytes:
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)


def png(width: int = 1, height: int = 1, pixel: bytes = b"\x12\x34\x56", padding: int = 0) -> bytes:
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    raw = (b"\0" + pixel * width) * height
    body = b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", header)
    if padding:
        body += png_chunk(b"tEXt", b"padding\0" + b"x" * padding)
    return body + png_chunk(b"IDAT", zlib.compress(raw)) + png_chunk(b"IEND", b"")


