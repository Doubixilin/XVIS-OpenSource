class ImageValidationTests(unittest.TestCase):
    def test_png_jpeg_have_real_bounded_dimensions(self):
        self.assertEqual(images.inspect(png(5, 3), "image/png"), (5, 3))
        self.assertEqual(images.inspect(png(1024, 1024), "image/png"), (1024, 1024))
        self.assertEqual(images.inspect(JPEG, "image/jpeg"), (1, 1))

    def test_spoofed_mime_corruption_truncation_and_dimensions_reject(self):
        oversized = b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", struct.pack(">IIBBBBB", 4097, 1, 8, 2, 0, 0, 0))
        excessive_pixels = b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", struct.pack(">IIBBBBB", 4096, 4096, 8, 2, 0, 0, 0))
        broken_crc = bytearray(png()); broken_crc[-1] ^= 1
        for body, mime in ((png(), "image/jpeg"), (JPEG, "image/png"), (bytes(broken_crc), "image/png"),
                           (png()[:-1], "image/png"), (JPEG[:-2], "image/jpeg"),
                           (oversized, "image/png"), (excessive_pixels, "image/png"), (b"GIF89a", "image/png")):
            with self.subTest(mime=mime, size=len(body)), self.assertRaises(repo.RepoError):
                images.inspect(body, mime)

    def test_png_decompression_cannot_exceed_its_declared_surface(self):
        body = (b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
                + png_chunk(b"IDAT", zlib.compress(b"\0" * 1000000)) + png_chunk(b"IEND", b""))
        with self.assertRaises(repo.RepoError):
            images.inspect(body, "image/png")

    def test_additive_migration_preserves_tasks_old_fingerprints_and_legacy_tables(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "hub.db"
            conn = init_v1_db(path)
            task, _ = repo.create_task(conn, "existing", "original-hash", "mac-a", "p", "旧任务", 30)
            before = list(conn.execute("PRAGMA table_info(v1_tasks)"))
            with conn:
                conn.execute("DROP TABLE v1_task_images"); conn.execute("DROP TABLE v1_images")
                conn.execute("CREATE TABLE legacy(value TEXT)"); conn.execute("INSERT INTO legacy VALUES('保留')")
            conn.close()
            conn = init_v1_db(path)
            self.assertEqual([tuple(row) for row in conn.execute("PRAGMA table_info(v1_tasks)")], [tuple(row) for row in before])
            self.assertEqual(repo.require_task(conn, task["task_id"])["request_hash"], "original-hash")
            self.assertEqual(conn.execute("SELECT value FROM legacy").fetchone()[0], "保留")
            self.assertEqual(repo.task_view(conn, repo.require_task(conn, task["task_id"]))["images"], [])
            conn.close()

    def test_empty_image_array_keeps_legacy_hash_and_order_changes_hash(self):
        body = {"client_request_id": "old", "node_id": "mac-a", "project_id": "p", "prompt": "原文"}
        expected = hashlib.sha256(repo.dump({"operation": "create", **body}).encode()).hexdigest()
        self.assertEqual(repo.request_fingerprint("create", TaskCreate(**body).model_dump()), expected)
        self.assertEqual(repo.request_fingerprint("create", {**body, "image_ids": []}), expected)
        first, second = image_id(), image_id()
        self.assertNotEqual(repo.request_fingerprint("create", {**body, "image_ids": [first, second]}),
                            repo.request_fingerprint("create", {**body, "image_ids": [second, first]}))

    def test_atomic_write_failure_and_fixed_id_symlink_do_not_commit(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary); conn = init_v1_db(directory / "hub.db")
            store = images.ImageStore(str(directory / "hub.db"))
            ident = image_id()
            with patch("hub.gateway.images.os.replace", side_effect=OSError("test-only-full")):
                with self.assertRaises(repo.RepoError) as failure:
                    store.put(conn, ident, png(), "image/png")
            self.assertEqual(failure.exception.code, "image_storage_error")
            self.assertEqual(list(store.directory.iterdir()), [])
            self.assertEqual(conn.execute("SELECT COUNT(*) FROM v1_images").fetchone()[0], 0)
            outside = directory / "outside"; outside.write_bytes(b"keep")
            (store.directory / ident).symlink_to(outside)
            with self.assertRaises(repo.RepoError):
                store.put(conn, ident, png(), "image/png")
            self.assertEqual(outside.read_bytes(), b"keep")
            for bad in ("../outside", "i-" + "A" * 32, "i-" + "0" * 31, "i-" + "0" * 32 + "/x"):
                with self.assertRaises(repo.RepoError):
                    store.put(conn, bad, png(), "image/png")
            conn.close()


